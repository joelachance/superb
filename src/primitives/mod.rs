//! # primitives
//!
//! Foundation types shared by every Superb SDK crate. This crate has **no
//! dependencies** and performs **no I/O**; everything here is `Copy`-friendly
//! and safe to use on the audio thread.
//!
//! * [`SampleRate`] — integer sample rate with float helpers.
//! * [`TimePosition`] / [`TimeDuration`] — sample-accurate positions on the
//!   audio timeline (signed, so pre-roll is representable).
//! * [`BeatPosition`] / [`BeatDuration`] — musical positions in quarter notes.
//! * [`TimeSignature`] — meter as `numerator / denominator`.
//! * ID newtypes ([`TrackId`], [`NodeId`], ...) generated by [`IdGenerator`].
//! * [`SuperbError`] — the shared error enum.
//!
//! ```
//! use superb::primitives::{SampleRate, TimePosition, BeatPosition};
//!
//! let rate = SampleRate::new(48_000).unwrap();
//! let half_second = TimePosition::from_seconds(0.5, rate);
//! assert_eq!(half_second.samples(), 24_000);
//! assert_eq!(half_second.to_seconds(rate), 0.5);
//!
//! // Beats are independent of sample rate; the tempo map in
//! // `primitives::transport` converts between the two domains.
//! let two_bars_of_4_4 = BeatPosition::new(8.0);
//! assert_eq!(two_bars_of_4_4.beats(), 8.0);
//! ```

